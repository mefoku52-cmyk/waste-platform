#!/data/data/com.termux/files/usr/bin/bash

set -u

PROJECT_ROOT="$(pwd)"
REPORT="$PROJECT_ROOT/audit-output/p0_02_r15_secret_provenance_expected_count_closure.txt"

mkdir -p "$PROJECT_ROOT/audit-output"

exec > >(tee "$REPORT") 2>&1

FAILURE_COUNT=0
REVIEW_COUNT=0

pass() {
    echo "PASS: $*"
}

fail() {
    echo "FAIL: $*"
    FAILURE_COUNT=$((FAILURE_COUNT + 1))
}

review() {
    echo "REVIEW: $*"
    REVIEW_COUNT=$((REVIEW_COUNT + 1))
}

section() {
    echo
    echo "============================================================"
    echo "$1"
    echo "============================================================"
}

log() {
    echo "$*"
}

section "P0-02 R15 SECRET PROVENANCE EXPECTED COUNT CLOSURE"

section "1. SAFETY PRECHECK"

if [ -d "$PROJECT_ROOT" ]; then
    pass "PROJECT_ROOT_CONFIRMED=$PROJECT_ROOT"
else
    fail "PROJECT_ROOT_NOT_FOUND"
fi

pass "READ_ONLY=YES"
pass "NO_SOURCE_WRITES=YES"
pass "NO_RUNTIME_EXECUTION=YES"
pass "NO_ENV_EXECUTION=YES"
pass "NO_BUILD=YES"
pass "NO_DEPLOYMENT=YES"
pass "NO_DELETIONS=YES"
pass "NO_SECRET_VALUES_PRINTED=YES"
pass "BOUNDED_SCAN=YES"

section "2. REQUIRED AUTHORITY FILES"

ENV_FILE=".env.production"
COMPOSE_FILE="docker-compose.yml"
RUNTIME_FILE="app/core/config.py"
CI_FILE=".github/workflows/ci.yml"
DEPLOY_FILE="scripts/deploy.sh"

for f in \
    "$ENV_FILE" \
    "$COMPOSE_FILE" \
    "$RUNTIME_FILE" \
    "$CI_FILE" \
    "$DEPLOY_FILE"
do
    if [ -f "$f" ]; then
        pass "AUTHORITY_PRESENT=$f"
    else
        fail "AUTHORITY_MISSING=$f"
    fi
done

section "3. SECRET TOKEN SET"

SECRET_KEYS=(
    POSTGRES_PASSWORD
    DATABASE_PASSWORD
    JWT_SECRET_KEY
    JWT_REFRESH_SECRET_KEY
    S3_SECRET_KEY
)

for key in "${SECRET_KEYS[@]}"; do
    log "SECRET_TOKEN=$key"
done

section "4. PRODUCTION ENV AUTHORITY"

ENV_SECRET_COUNT=0

for key in "${SECRET_KEYS[@]}"; do
    if grep -Eq "^${key}=" "$ENV_FILE"; then
        pass "ENV_AUTHORITY_PRESENT KEY=$key VALUE=<REDACTED>"
        ENV_SECRET_COUNT=$((ENV_SECRET_COUNT + 1))
    else
        fail "ENV_AUTHORITY_MISSING KEY=$key"
    fi
done

log "ENV_SECRET_COUNT=$ENV_SECRET_COUNT"

if [ "$ENV_SECRET_COUNT" -eq "${#SECRET_KEYS[@]}" ]; then
    pass "PRODUCTION_SECRET_AUTHORITY_COMPLETE"
else
    fail "PRODUCTION_SECRET_AUTHORITY_INCOMPLETE"
fi

section "5. COMPOSE TOKEN SEMANTIC ANALYSIS"

EXPECTED_COMPOSE_KEYS=(
    POSTGRES_PASSWORD
    JWT_SECRET_KEY
    JWT_REFRESH_SECRET_KEY
)

COMPOSE_TARGET_COUNT="${#EXPECTED_COMPOSE_KEYS[@]}"
COMPOSE_REFERENCE_COUNT=0
COMPOSE_LITERAL_COUNT=0
COMPOSE_NON_SECRET_CONTEXT_COUNT=0
EXPECTED_COMPOSE_REFERENCE_COUNT=0
MISSING_COMPOSE_REFERENCE_COUNT=0

for key in "${EXPECTED_COMPOSE_KEYS[@]}"; do

    # Accept explicit Compose interpolation forms:
    # ${KEY}
    # ${KEY:-default}
    # ${KEY:?error}
    if grep -Eq "\\\$\{${key}([}:]|:-|:\?)" "$COMPOSE_FILE"; then
        pass "COMPOSE_REFERENCE_WIRING KEY=$key VALUE=<REDACTED>"
        COMPOSE_REFERENCE_COUNT=$((COMPOSE_REFERENCE_COUNT + 1))
        EXPECTED_COMPOSE_REFERENCE_COUNT=$((EXPECTED_COMPOSE_REFERENCE_COUNT + 1))
    else
        fail "COMPOSE_REFERENCE_MISSING KEY=$key"
        MISSING_COMPOSE_REFERENCE_COUNT=$((MISSING_COMPOSE_REFERENCE_COUNT + 1))
    fi

    # Literal assignment must contain a non-interpolation value.
    if grep -Eq "^[[:space:]]*${key}:[[:space:]]*[^[:space:]#\"']" "$COMPOSE_FILE"; then
        if ! grep -Eq "\\\$\{${key}([}:]|:-|:\?)" "$COMPOSE_FILE"; then
            COMPOSE_LITERAL_COUNT=$((COMPOSE_LITERAL_COUNT + 1))
        fi
    fi
done

# DATABASE_URL is deliberately non-target secret context.
if grep -Eq "DATABASE_URL:.*\\\$\{POSTGRES_PASSWORD" "$COMPOSE_FILE"; then
    COMPOSE_NON_SECRET_CONTEXT_COUNT=$((COMPOSE_NON_SECRET_CONTEXT_COUNT + 1))
    pass "DATABASE_URL_SECRET_REFERENCE_CONTEXT_PRESENT"
fi

log "COMPOSE_TARGET_COUNT=$COMPOSE_TARGET_COUNT"
log "COMPOSE_REFERENCE_COUNT=$COMPOSE_REFERENCE_COUNT"
log "COMPOSE_LITERAL_COUNT=$COMPOSE_LITERAL_COUNT"
log "COMPOSE_NON_SECRET_CONTEXT_COUNT=$COMPOSE_NON_SECRET_CONTEXT_COUNT"
log "EXPECTED_COMPOSE_REFERENCE_COUNT=$EXPECTED_COMPOSE_REFERENCE_COUNT"
log "MISSING_COMPOSE_REFERENCE_COUNT=$MISSING_COMPOSE_REFERENCE_COUNT"

section "6. EXPECTED COUNT SELF-CONSISTENCY"

# The expected count is the cardinality of the explicitly declared
# production Compose wiring set, not the number of all secret tokens.
if [ "$EXPECTED_COMPOSE_REFERENCE_COUNT" -eq "$COMPOSE_TARGET_COUNT" ]; then
    pass "EXPECTED_REFERENCE_COUNT_EQUALS_TARGET_COUNT"
else
    fail "EXPECTED_REFERENCE_COUNT_TARGET_MISMATCH"
fi

if [ "$COMPOSE_REFERENCE_COUNT" -eq "$EXPECTED_COMPOSE_REFERENCE_COUNT" ]; then
    pass "ACTUAL_REFERENCE_COUNT_EQUALS_EXPECTED_REFERENCE_COUNT"
else
    fail "ACTUAL_REFERENCE_COUNT_EXPECTED_REFERENCE_COUNT_MISMATCH"
fi

if [ "$MISSING_COMPOSE_REFERENCE_COUNT" -eq 0 ]; then
    pass "NO_EXPECTED_COMPOSE_REFERENCE_MISSING"
else
    fail "EXPECTED_COMPOSE_REFERENCE_MISSING_COUNT=$MISSING_COMPOSE_REFERENCE_COUNT"
fi

if [ "$COMPOSE_LITERAL_COUNT" -eq 0 ]; then
    pass "NO_LITERAL_COMPOSE_SECRET_ASSIGNMENT"
else
    fail "LITERAL_COMPOSE_SECRET_ASSIGNMENT_COUNT=$COMPOSE_LITERAL_COUNT"
fi

section "7. R13/R14 FALSE-FAILURE GUARD"

# R13 failed despite discovering all three valid references.
# R14 failed because its expected count was inflated to six.
# This closure accepts only the semantically proven cardinality:
# 3 declared production Compose secret wiring targets.

if [ "$COMPOSE_REFERENCE_COUNT" -eq 3 ] \
   && [ "$COMPOSE_LITERAL_COUNT" -eq 0 ] \
   && [ "$MISSING_COMPOSE_REFERENCE_COUNT" -eq 0 ] \
   && [ "$EXPECTED_COMPOSE_REFERENCE_COUNT" -eq 3 ]; then
    pass "R13_R14_FALSE_FAILURE_CONDITION_RESOLVED"
else
    fail "R13_R14_FALSE_FAILURE_CONDITION_REMAINS"
fi

section "8. RUNTIME JWT SECRET AUTHORITY"

RUNTIME_DECLARATION_COUNT=0
RUNTIME_CONTEXT_COUNT=0
RUNTIME_LITERAL_COUNT=0

if grep -Eq "JWT_SECRET_KEY[[:space:]]*:[[:space:]]*str" "$RUNTIME_FILE"; then
    pass "RUNTIME_JWT_SECRET_DECLARATION_PRESENT"
    RUNTIME_DECLARATION_COUNT=1
else
    fail "RUNTIME_JWT_SECRET_DECLARATION_MISSING"
fi

RUNTIME_CONTEXT_COUNT="$(
    grep -E \
        "JWT_SECRET_KEY|JWT_REFRESH_SECRET_KEY" \
        "$RUNTIME_FILE" |
    grep -E \
        "settings|config|BaseSettings|Field|secret" |
    wc -l |
    tr -d ' '
)"

if [ -z "$RUNTIME_CONTEXT_COUNT" ]; then
    RUNTIME_CONTEXT_COUNT=0
fi

if [ "$RUNTIME_CONTEXT_COUNT" -ge 2 ]; then
    pass "RUNTIME_JWT_SECRET_USE_CONTEXT_PRESENT COUNT=$RUNTIME_CONTEXT_COUNT"
else
    review "RUNTIME_JWT_SECRET_USE_CONTEXT_REVIEW COUNT=$RUNTIME_CONTEXT_COUNT"
fi

if grep -Eq \
    "^[[:space:]]*(JWT_SECRET_KEY|JWT_REFRESH_SECRET_KEY)[[:space:]]*=[[:space:]]*['\"]" \
    "$RUNTIME_FILE"; then
    RUNTIME_LITERAL_COUNT=1
    fail "LITERAL_RUNTIME_SECRET_ASSIGNMENT_DETECTED"
else
    pass "NO_LITERAL_RUNTIME_SECRET_ASSIGNMENT"
fi

log "RUNTIME_DECLARATION_COUNT=$RUNTIME_DECLARATION_COUNT"
log "RUNTIME_CONTEXT_COUNT=$RUNTIME_CONTEXT_COUNT"
log "RUNTIME_LITERAL_COUNT=$RUNTIME_LITERAL_COUNT"

section "9. CI TEST-SCOPE PROVENANCE"

CI_SECRET_ASSIGNMENT_COUNT=0
CI_TEST_SCOPE_COUNT=0
CI_PROD_SCOPE_COUNT=0

for key in "${SECRET_KEYS[@]}"; do
    if grep -Eq "${key}[[:space:]]*:" "$CI_FILE"; then
        CI_SECRET_ASSIGNMENT_COUNT=$((CI_SECRET_ASSIGNMENT_COUNT + 1))
        CI_TEST_SCOPE_COUNT=$((CI_TEST_SCOPE_COUNT + 1))
        pass "CI_SECRET_TEST_SCOPE KEY=$key VALUE=<REDACTED>"
    fi
done

log "CI_SECRET_ASSIGNMENT_COUNT=$CI_SECRET_ASSIGNMENT_COUNT"
log "CI_TEST_SCOPE_COUNT=$CI_TEST_SCOPE_COUNT"
log "CI_PROD_SCOPE_COUNT=$CI_PROD_SCOPE_COUNT"

if [ "$CI_PROD_SCOPE_COUNT" -eq 0 ]; then
    pass "CI_HAS_NO_DETECTED_PRODUCTION_SECRET_SCOPE"
else
    fail "CI_PRODUCTION_SECRET_SCOPE_DETECTED"
fi

section "10. DEPLOYMENT AUTHORITY BOUNDARY"

DEPLOY_SECRET_REFERENCE_COUNT=0

if grep -Eq \
    "POSTGRES_PASSWORD|DATABASE_PASSWORD|JWT_SECRET_KEY|JWT_REFRESH_SECRET_KEY|S3_SECRET_KEY" \
    "$DEPLOY_FILE"; then
    DEPLOY_SECRET_REFERENCE_COUNT=1
    fail "DEPLOY_SCRIPT_HAS_DIRECT_SECRET_IDENTIFIER_REFERENCE"
else
    pass "DEPLOY_SCRIPT_HAS_NO_DIRECT_SECRET_IDENTIFIER_REFERENCE"
fi

if grep -Eq \
    "\.env\.production|env_file|docker-compose|docker compose" \
    "$DEPLOY_FILE"; then
    pass "DEPLOY_SCRIPT_REFERENCES_AUTHORITY_BOUNDARY"
else
    review "DEPLOY_SCRIPT_AUTHORITY_BOUNDARY_NOT_EXPLICIT"
fi

section "11. SECRET VALUE OUTPUT GUARD"

SECRET_VALUE_OUTPUT_COUNT=0

if grep -Eq \
    "echo.*(POSTGRES_PASSWORD|DATABASE_PASSWORD|JWT_SECRET_KEY|JWT_REFRESH_SECRET_KEY|S3_SECRET_KEY).*=" \
    "$COMPOSE_FILE" "$RUNTIME_FILE" "$CI_FILE" "$DEPLOY_FILE" 2>/dev/null; then
    SECRET_VALUE_OUTPUT_COUNT=1
    fail "SECRET_VALUE_OUTPUT_PATTERN_DETECTED"
else
    pass "SECRET_VALUE_OUTPUT_REMAINED_REDACTED"
fi

log "SECRET_VALUE_OUTPUT_COUNT=$SECRET_VALUE_OUTPUT_COUNT"

section "12. CROSS-AUTHORITY INVARIANTS"

if [ "$ENV_SECRET_COUNT" -eq 5 ]; then
    pass "INVARIANT_PRODUCTION_SECRET_SET_EXACT"
else
    fail "INVARIANT_PRODUCTION_SECRET_SET"
fi

if [ "$COMPOSE_REFERENCE_COUNT" -eq 3 ] \
   && [ "$MISSING_COMPOSE_REFERENCE_COUNT" -eq 0 ]; then
    pass "INVARIANT_REQUIRED_COMPOSE_SECRET_REFERENCES_PRESENT"
else
    fail "INVARIANT_REQUIRED_COMPOSE_SECRET_REFERENCES"
fi

if [ "$COMPOSE_LITERAL_COUNT" -eq 0 ]; then
    pass "INVARIANT_NO_LITERAL_COMPOSE_SECRET"
else
    fail "INVARIANT_LITERAL_COMPOSE_SECRET"
fi

if [ "$RUNTIME_LITERAL_COUNT" -eq 0 ]; then
    pass "INVARIANT_NO_LITERAL_RUNTIME_SECRET"
else
    fail "INVARIANT_LITERAL_RUNTIME_SECRET"
fi

if [ "$CI_PROD_SCOPE_COUNT" -eq 0 ]; then
    pass "INVARIANT_NO_CI_PRODUCTION_SECRET_SCOPE"
else
    fail "INVARIANT_CI_PRODUCTION_SECRET_SCOPE"
fi

if [ "$SECRET_VALUE_OUTPUT_COUNT" -eq 0 ]; then
    pass "INVARIANT_NO_SECRET_VALUE_OUTPUT"
else
    fail "INVARIANT_SECRET_VALUE_OUTPUT"
fi

section "13. FINAL CLASSIFICATION"

log "FAILURE_COUNT=$FAILURE_COUNT"
log "REVIEW_COUNT=$REVIEW_COUNT"
log "ENV_SECRET_COUNT=$ENV_SECRET_COUNT"
log "COMPOSE_TARGET_COUNT=$COMPOSE_TARGET_COUNT"
log "COMPOSE_REFERENCE_COUNT=$COMPOSE_REFERENCE_COUNT"
log "COMPOSE_LITERAL_COUNT=$COMPOSE_LITERAL_COUNT"
log "COMPOSE_NON_SECRET_CONTEXT_COUNT=$COMPOSE_NON_SECRET_CONTEXT_COUNT"
log "RUNTIME_DECLARATION_COUNT=$RUNTIME_DECLARATION_COUNT"
log "RUNTIME_CONTEXT_COUNT=$RUNTIME_CONTEXT_COUNT"
log "RUNTIME_LITERAL_COUNT=$RUNTIME_LITERAL_COUNT"
log "CI_SECRET_ASSIGNMENT_COUNT=$CI_SECRET_ASSIGNMENT_COUNT"
log "CI_TEST_SCOPE_COUNT=$CI_TEST_SCOPE_COUNT"
log "CI_PROD_SCOPE_COUNT=$CI_PROD_SCOPE_COUNT"
log "DEPLOY_SECRET_REFERENCE_COUNT=$DEPLOY_SECRET_REFERENCE_COUNT"
log "SECRET_VALUE_OUTPUT_COUNT=$SECRET_VALUE_OUTPUT_COUNT"
log "EXPECTED_COMPOSE_REFERENCE_COUNT=$EXPECTED_COMPOSE_REFERENCE_COUNT"
log "MISSING_COMPOSE_REFERENCE_COUNT=$MISSING_COMPOSE_REFERENCE_COUNT"

if [ "$FAILURE_COUNT" -gt 0 ]; then
    STATUS="FAIL"
    RESULT="P0_02_R15_SECRET_PROVENANCE_EXPECTED_COUNT_CLOSURE_FAILURE"
    EXIT_CODE=20
elif [ "$REVIEW_COUNT" -gt 0 ]; then
    STATUS="REVIEW"
    RESULT="P0_02_R15_SECRET_PROVENANCE_EXPECTED_COUNT_CLOSURE_REVIEW_REQUIRED"
    EXIT_CODE=10
else
    STATUS="CLEAN"
    RESULT="P0_02_R15_SECRET_PROVENANCE_EXPECTED_COUNT_CLOSURE_CLEAN"
    EXIT_CODE=0
fi

log "P0_02_R15_STATUS=$STATUS"
log "RESULT=$RESULT"
log "EXIT_CODE=$EXIT_CODE"
log "REPORT=$REPORT"

exit "$EXIT_CODE"
